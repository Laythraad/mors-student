"""Arabic message bank for Mors + the tone guard-rail.

Two hard rules live here:

1. **Motivation, never manipulation.** `assert_tone()` refuses any template
   that shames, insults, threatens or guilts the student, and a unit test runs
   it over *every* message in this file so a bad string can never ship.
2. **Contextual, not score-based.** Templates are keyed by *situation*
   (`improvement_from_low`, `high_score_but_weak_foundation`, …), so the
   engine picks the words from what happened, not from a raw number.
"""

from __future__ import annotations

import re


class ToneViolation(AssertionError):
    """Raised when a message would manipulate instead of motivate."""


